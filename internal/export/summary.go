package export

import (
	"fmt"
	"strings"

	"github.com/open-security-tooling/threat-model/internal/check"
	"github.com/open-security-tooling/threat-model/internal/ops"
)

// SummaryMarker starts every summary, so the GitHub Action can find the
// comment it posted before and update it instead of adding another.
const SummaryMarker = "<!-- threat-model-summary -->"

const (
	// shown is how many items a list shows before the rest are folded into
	// a collapsed <details> block.
	shown = 5
	// maxItems caps each list, so a huge model can't produce a comment
	// longer than GitHub accepts (65,536 characters).
	maxItems = 50
	// topRisks is how many open threats the summary lists.
	topRisks = 5
)

// PRSummary renders the Markdown for one pull request comment or job
// summary: what changed, what needs a person to agree, findings by
// severity and the top open risks. v may be nil (for example when the
// model can't be parsed); then the open risks are left out.
func PRSummary(r check.Result, v *ops.View) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("%s\n## Threat model check\n\n", SummaryMarker)
	switch {
	case r.Errors > 0:
		w("❌ **%s, %s.**", plural(r.Errors, "error"), plural(r.Warnings, "warning"))
	case r.Warnings > 0:
		w("⚠️ **No errors, %s.**", plural(r.Warnings, "warning"))
	default:
		w("✅ **No problems found.**")
	}
	if r.Policy != "" {
		w(" Policy: %s.", code(r.Policy))
	}
	w("\n\n")

	if ch := r.Changes; ch != nil {
		w("%s\n\n", mdEscape(ch.Summary))
		var items []string
		for _, t := range ch.ThreatsAdded {
			items = append(items, fmt.Sprintf("Added %s %s (%s)", code(t.ID), mdEscape(t.Title), levelText(t.Level)))
		}
		for _, t := range ch.ThreatsRemoved {
			items = append(items, fmt.Sprintf("Removed %s %s (was %s)", code(t.ID), mdEscape(t.Title), levelText(t.Level)))
		}
		for _, c := range ch.RiskRaised {
			items = append(items, fmt.Sprintf("Risk raised: %s %s, %s → %s", code(c.ID), mdEscape(c.Title), levelText(c.From), levelText(c.To)))
		}
		for _, c := range ch.RiskLowered {
			items = append(items, fmt.Sprintf("Risk lowered: %s %s, %s → %s because %s", code(c.ID), mdEscape(c.Title), levelText(c.From), levelText(c.To), mdEscape(c.Reason)))
		}
		for _, s := range ch.StatusChanged {
			items = append(items, fmt.Sprintf("Status: %s %s, %s → %s", code(s.ID), mdEscape(s.Title), mdEscape(s.From), mdEscape(s.To)))
		}
		for _, id := range ch.MitigationsDone {
			items = append(items, fmt.Sprintf("Mitigation done: %s", code(id)))
		}
		if len(items) > 0 {
			w("### What changed\n\n")
			writeList(&b, items, "changes")
		}
		if len(ch.NeedsApproval) > 0 {
			w("### Needs a person to agree\n\n")
			w("These changes lower risk without finishing a fix. That can be right, but it's also the easiest way to make a threat model say something untrue.")
			if len(ch.Approvers) > 0 {
				names := make([]string, len(ch.Approvers))
				for i, a := range ch.Approvers {
					names[i] = handle(a)
				}
				w(" One of %s should approve this pull request.", strings.Join(names, " or "))
			} else {
				w(" Make sure a reviewer agrees with each one.")
			}
			w("\n\n")
			items := make([]string, len(ch.NeedsApproval))
			for i, msg := range ch.NeedsApproval {
				items[i] = mdEscape(msg)
			}
			writeList(&b, items, "changes")
		}
	}

	var errs, warns []string
	for _, f := range r.Findings {
		line := mdEscape(f.Message)
		if f.Hint != "" {
			line += " _" + mdEscape(f.Hint) + "_"
		}
		if f.Severity == check.SevError {
			errs = append(errs, line)
		} else {
			warns = append(warns, line)
		}
	}
	if len(errs) > 0 {
		w("### Errors\n\n")
		writeList(&b, errs, "errors")
	}
	if len(warns) > 0 {
		w("### Warnings\n\n")
		writeList(&b, warns, "warnings")
	}

	if v != nil && v.Model != nil {
		open := openThreats(v)
		if len(open) > 0 {
			w("### Top open risks\n\n| Risk | Threat |\n|---|---|\n")
			for i, t := range open {
				if i == topRisks {
					break
				}
				w("| %s | %s %s |\n", levelBadge(v.Risks[t.ID].Level), code(t.ID), mdEscape(t.Title))
			}
			if n := len(open) - topRisks; n > 0 {
				w("\n%s more open. Run `threat report` for all of them.\n", plural(n, "threat"))
			}
			w("\n")
		}
	}
	w("_Generated by `threat check`. Run it locally to see the same result._\n")
	return b.String()
}

// writeList writes items as a bulleted list; past the first few they go in
// a collapsed block, and past maxItems they're counted, not listed.
func writeList(b *strings.Builder, items []string, what string) {
	for i, it := range items {
		if i == maxItems {
			fmt.Fprintf(b, "- …and %d more. Run `threat check` locally to see them all.\n", len(items)-maxItems)
			break
		}
		if i == shown {
			fmt.Fprintf(b, "\n<details><summary>%d more %s</summary>\n\n", len(items)-shown, what)
		}
		fmt.Fprintf(b, "- %s\n", it)
	}
	if len(items) > shown {
		b.WriteString("\n</details>\n")
	}
	b.WriteString("\n")
}

// handle shows a GitHub user or team as inline code, which GitHub doesn't
// turn into a mention, so updating the comment doesn't ping anyone.
func handle(s string) string {
	if strings.HasPrefix(s, "@") && safeID.MatchString(s[1:]) {
		return "`" + s + "`"
	}
	return mdEscape(s)
}

func plural(n int, word string) string {
	if n == 1 {
		return "1 " + word
	}
	return fmt.Sprintf("%d %ss", n, word)
}
