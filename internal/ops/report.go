package ops

// Markdown report for PRs, wikis and audits.

import (
	"fmt"
	"sort"
	"strings"

	"github.com/open-security-tooling/threat-model/internal/model"
	"github.com/open-security-tooling/threat-model/internal/risk"
)

var badge = map[string]string{"critical": "🟥 Critical", "high": "🟧 High", "medium": "🟨 Medium", "low": "🟩 Low", "": "⬜ Not assessed"}

// ReportMarkdown renders the report. Model text is escaped so a model can't inject
// links, images or HTML into wherever the report is rendered.
func ReportMarkdown(v View) string {
	m := v.Model
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("# Threat model: %s\n\n", mdEscape(m.System.Name))
	if m.System.Description != "" {
		w("%s\n\n", mdEscape(m.System.Description))
	}
	s := v.Summary
	w("%d components, %d flows, %d threats (%d open).\n\n", s.Components, s.Flows, s.Threats, s.Open)
	w("| Risk | Threats |\n|---|---|\n")
	for i := len(risk.Levels) - 1; i >= 0; i-- {
		w("| %s | %d |\n", badge[risk.Levels[i]], s.ByRisk[risk.Levels[i]])
	}
	if s.NotAssessed > 0 {
		w("| %s | %d |\n", badge[""], s.NotAssessed)
	}
	w("\n")

	threats := append([]model.Threat(nil), m.Threats...)
	sort.SliceStable(threats, func(i, j int) bool {
		ri, rj := v.Risks[threats[i].ID], v.Risks[threats[j].ID]
		if (threats[i].Status == "not-applicable") != (threats[j].Status == "not-applicable") {
			return threats[j].Status == "not-applicable"
		}
		return risk.Rank(ri.Level) > risk.Rank(rj.Level)
	})

	w("## Threats\n\n")
	for _, t := range threats {
		if t.Status == "not-applicable" {
			continue
		}
		a := v.Risks[t.ID]
		w("### %s: %s\n\n", badge[a.Level], mdEscape(t.Title))
		w("`%s` · %s", t.ID, statusText(t))
		if names := affects(m, t); names != "" {
			w(" · affects %s", names)
		}
		w("\n\n")
		if len(t.Attack) > 0 {
			w("**How it works**\n\n")
			for i, step := range t.Attack {
				w("%d. %s\n", i+1, mdEscape(step))
			}
			w("\n")
		}
		w("**Why this risk:** %s\n\n", mdEscape(a.Why))
		if len(a.Changes) > 0 {
			w("**Fixes**\n\n")
			for _, c := range a.Changes {
				w("- [%s] %s (%s → %s once done)\n", checkbox(c.Status), mdEscape(c.Title), c.From, c.To)
			}
			w("\n")
		}
		if t.Status == "accepted" && t.Accepted != nil {
			w("> Accepted by %s until %s: %s\n\n", mdEscape(t.Accepted.By), t.Accepted.Until, mdEscape(t.Accepted.Reason))
		}
	}

	var dismissed []model.Threat
	for _, t := range threats {
		if t.Status == "not-applicable" {
			dismissed = append(dismissed, t)
		}
	}
	if len(dismissed) > 0 {
		w("## Considered and ruled out\n\n")
		for _, t := range dismissed {
			w("- %s: %s\n", mdEscape(t.Title), mdEscape(t.Reason))
		}
		w("\n")
	}

	w("## Components\n\n| Component | Kind | Zone | Reviewed |\n|---|---|---|---|\n")
	for _, c := range m.Components {
		zone := c.Zone
		if z := m.Zone(c.Zone); z != nil {
			zone = z.Name
		}
		w("| %s | %s | %s | %s |\n", cell(c.Name), c.Kind, cell(zone), or(c.Reviewed, "never"))
	}
	w("\n_Generated by `threat report`._\n")
	return b.String()
}

func statusText(t model.Threat) string {
	switch t.Status {
	case "open":
		return "open"
	case "mitigated":
		return "mitigated"
	case "accepted":
		return "accepted risk"
	}
	return t.Status
}

func checkbox(status string) string {
	switch status {
	case "done":
		return "x"
	case "in-progress":
		return "~"
	}
	return " "
}

func affects(m *model.Model, t model.Threat) string {
	var names []string
	for _, a := range t.Affects {
		if c := m.Component(a); c != nil {
			names = append(names, mdEscape(c.Name))
		} else if f := m.Flow(a); f != nil {
			names = append(names, "`"+f.ID+"`")
		}
	}
	return strings.Join(names, ", ")
}

func or(s, def string) string {
	if s == "" {
		return def
	}
	return s
}

// esc neutralises Markdown and HTML in model text.
func mdEscape(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch r {
		case '\\', '`', '*', '_', '[', ']', '<', '>', '#', '|', '!', '~':
			b.WriteRune('\\')
			b.WriteRune(r)
		case '\n', '\r':
			b.WriteRune(' ')
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

func cell(s string) string { return mdEscape(s) }

// ReportResult is returned by Report.
type ReportResult struct {
	Markdown string `json:"markdown"`
}

// Report renders the model as Markdown.
func Report(source []byte) (ReportResult, error) {
	v, err := Show(source)
	if err != nil {
		return ReportResult{}, err
	}
	return ReportResult{Markdown: ReportMarkdown(v)}, nil
}
